"""The roadmap issue: one issue whose body shows every lane ticket by wave, a Blocked-by graph (mermaid) and counts
per lane. Created by `setup`/`init`, refreshed by the planner and after each merge, always by the PAT's login."""
from __future__ import annotations

import re
from collections import Counter, defaultdict

from . import protocol as ns
from .config import Config
from .gh import GH
from .rules import label_names, lanes_of, parse_deps, wave_of

LABEL = "roadmap"
TITLE = "Night-shift roadmap"
MAX_NODES = 80
STATUSES = ("done", "in progress", "blocked", "waiting", "ready", "human", "proposed", "open")


def status_of(issue: dict, cfg: Config, open_numbers: set[int]) -> str:
    names = label_names(issue)
    if issue.get("state") == "closed":
        return "done"
    if cfg.label("in_progress") in names:
        return "in progress"
    if names & {cfg.label("blocked"), cfg.label("needs_human")}:
        return "blocked"
    if "waiting" in names or any(d in open_numbers or d < 0 for d in parse_deps(issue.get("body"))):
        return "waiting"
    if cfg.label("human") in names:
        return "human"
    if cfg.label("proposed") in names:
        return "proposed"
    if cfg.ready_label in names:
        return "ready"
    return "open"


def _text(value: str, limit: int = 70) -> str:
    """One line, no markup that could break the table or forge a marker."""
    flat = " ".join(str(value).split())[:limit]
    return ns.defang(flat.replace("|", "/"))


def _mermaid_label(value: str) -> str:
    # Mermaid labels sit in double quotes; entity codes keep quotes and brackets from closing them.
    flat = " ".join(str(value).split())[:40]
    return re.sub(r'["<>`\[\]{}()|#;]', lambda m: f"#{ord(m.group(0))};", flat)


def tickets(gh: GH, cfg: Config) -> list[dict]:
    lane_names = {lane.name for lane in cfg.lanes}
    skip = {cfg.label("night_log"), LABEL}
    return [i for i in gh.issues(state="all")
            if set(lanes_of(i)) & lane_names and not label_names(i) & skip]


def render(cfg: Config, issues: list[dict]) -> str:
    open_numbers = {i["number"] for i in issues if i.get("state") != "closed"}
    status = {i["number"]: status_of(i, cfg, open_numbers) for i in issues}
    by_wave: dict[int, list[dict]] = defaultdict(list)
    for i in issues:
        by_wave[wave_of(i)].append(i)

    lines = [ns.marker("roadmap"), f"# {TITLE}", "",
             "Generated by gh-nightshift from the issues; edits to this body are overwritten.", ""]
    total = Counter(status.values())
    done = total.get("done", 0)
    lines.append(f"**{done} of {len(issues)} tickets done.** "
                 + ", ".join(f"{s} {total[s]}" for s in STATUSES if total.get(s) and s != "done"))
    lines += ["", "## Lanes", "", "| Lane | " + " | ".join(STATUSES) + " |", "|---" * (len(STATUSES) + 1) + "|"]
    for lane in cfg.lanes:
        c = Counter(status[i["number"]] for i in issues if lane.name in lanes_of(i))
        lines.append(f"| {_text(lane.name)} | " + " | ".join(str(c.get(s, 0)) for s in STATUSES) + " |")

    for wave in sorted(by_wave):
        items = sorted(by_wave[wave], key=lambda i: i["number"])
        lines += ["", f"## Wave {wave}" if wave != 999 else "## No wave label", "",
                  "| # | Ticket | Lane | Status | Blocked by |", "|---|---|---|---|---|"]
        for i in items:
            deps = ", ".join(f"#{d}" if d > 0 else "unresolved" for d in parse_deps(i.get("body"))) or "-"
            lines.append(f"| #{i['number']} | {_text(i.get('title', ''))} | {_text(', '.join(lanes_of(i)))} | "
                         f"{status[i['number']]} | {deps} |")

    graph = [i for i in sorted(issues, key=lambda i: i["number"]) if status[i["number"]] != "done"
             or any(i["number"] in parse_deps(j.get("body")) for j in issues if j.get("state") != "closed")]
    if graph:
        shown = graph[:MAX_NODES]
        ids = {i["number"] for i in shown}
        lines += ["", "## Blocked-by graph", ""]
        if len(graph) > MAX_NODES:
            lines.append(f"Showing the first {MAX_NODES} of {len(graph)} open tickets.")
            lines.append("")
        lines += ["```mermaid", "graph LR"]
        for i in shown:
            n = i["number"]
            lines.append(f'  i{n}["#{n} {_mermaid_label(i.get("title", ""))}"]:::{status[n].replace(" ", "_")}')
        for i in shown:
            for d in parse_deps(i.get("body")):
                if d in ids:
                    lines.append(f"  i{d} --> i{i['number']}")
        lines += ["  classDef done fill:#d4edda", "  classDef in_progress fill:#fff3cd",
                  "  classDef blocked fill:#f8d7da", "  classDef waiting fill:#fef2c0", "```"]
    return "\n".join(lines) + "\n"


def find(gh: GH) -> dict | None:
    """The roadmap issue, only if the PAT's login (or a trusted login) opened it: a label alone is not proof."""
    for i in gh.issues(labels=[LABEL]):
        if (i.get("user") or {}).get("login") in gh.trusted:
            return i
    return None


def update(gh: GH, cfg: Config, create: bool = True) -> str:
    body = render(cfg, tickets(gh, cfg))
    current = find(gh)
    if current is None:
        if not create:
            return "no roadmap issue (run `gh nightshift setup`)"
        made = gh.create_issue(TITLE, body, [LABEL])
        return f"roadmap issue #{made.get('number', 0)} created (pin it)"
    if (current.get("body") or "") == body:
        return f"roadmap #{current['number']} already up to date"
    gh.patch(gh.r(f"issues/{current['number']}"), {"body": body})
    return f"roadmap #{current['number']} updated"


def safe_update(gh: GH, cfg: Config, create: bool = False) -> str:
    """Refreshing the roadmap must never break a merge or a plan run."""
    try:
        return update(gh, cfg, create=create)
    except Exception as err:  # noqa: BLE001
        return f"roadmap not updated ({type(err).__name__})"
