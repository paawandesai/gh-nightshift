def labels(cfg: Config) -> list[tuple[str, str, str]]:
    """(name, color, description) for every label the night shift uses."""
    out = [(f"lane:{lane.name}", "1d76db", f"Work owned by the {lane.name} lane") for lane in cfg.lanes]
    out += [(f"wave:{w}", "c5def5", f"Build wave {w}") for w in range(10)]
    renamed = {v: k for k, v in cfg.labels.items()}
    for name, (color, desc) in LABEL_COLORS.items():
        key = {"night-safe": "ready", "needs-human": "needs_human", "agent:in-progress": "in_progress",
               "night-log": "night_log"}.get(name, name)
        actual = cfg.labels.get(key, name) if key in cfg.labels else name
        out.append((actual, color, desc))
    del renamed
    return out


def _q(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def _github_auth(cfg: Config, pat: str = "secrets.AGENT_PAT") -> tuple[str, str]:
    """(extra `with:` lines, the GitHub secret line) for a caller job: the PAT, or the App id and private key."""
    if cfg.auth_mode == "app":
        return (f"\n      app_id: '{cfg.app_id}'",
                f"app_private_key: ${{{{ secrets.{cfg.app_key_secret} }}}}")
    return "", f"agent_pat: ${{{{ {pat} }}}}"


def _runners(cfg: Config, agent: bool = False, github: bool = True) -> str:
    """Extra `with:` lines choosing runners; nothing when they are the default GitHub-hosted ones."""
    out = ""
    if github and cfg.runner_github != ["ubuntu-latest"]:
        out += f"\n      runs_on: {_q(json.dumps(cfg.runner_github))}"
    if agent and cfg.runner_agent != ["ubuntu-latest"]:
        out += f"\n      agent_runs_on: {_q(json.dumps(cfg.runner_agent))}"
    return out


def lane_workflow(cfg: Config, ci_name: str = "CI", tool_repo: str = TOOL_REPO) -> str:
    ref = cfg.tool_ref
    jobs = []
    for lane in cfg.lanes:
        # A lane owner's own PAT falls back to AGENT_PAT while unset; both names are explicit.
        pat = f"secrets.{lane.pat_secret} || secrets.AGENT_PAT" if lane.pat_secret else "secrets.AGENT_PAT"
        app_with, github = _github_auth(cfg, pat)
        # An optional second Claude token, used only when the first cannot start a run. Still an explicit name.
        fallback = (f"\n      claude_token_fallback: ${{{{ secrets.{lane.fallback_token_secret} }}}}"
                    if lane.fallback_token_secret else "")
        jobs.append(f"""  lane-{lane.name}:
    if: vars.AGENTS_ENABLED == 'true'
    concurrency:
      group: night-shift-{lane.name}
      cancel-in-progress: false
    uses: {tool_repo}/.github/workflows/lane.yml@{ref}
    with:
      lane: {lane.name}
      main_branch: {cfg.main_branch}
      only_lane: ${{{{ inputs.lane || '' }}}}
      tool_repo: {tool_repo}
      tool_ref: {ref}{app_with}{_runners(cfg, agent=True)}
    secrets:
      claude_token: ${{{{ secrets.{lane.token_secret} }}}}{fallback}
      {github}
""")
    return f"""# Generated by `gh nightshift init` from .night-shift/config.yml. Re-run `gh nightshift init --regenerate`
# after changing lanes. One job per lane with explicit secret names: each lane's runners receive exactly
# that lane's Claude token (plus its fallback Claude token, if the lane names one) and its PAT (or the GitHub
# App key), never other secrets (no matrix secrets[...], no secrets: inherit).
name: night-shift

on:
  # Every merge into {cfg.main_branch} starts the next issue in every lane; the timer is the backstop.
  push:
    branches: [{cfg.main_branch}]
  # When a PR's checks finish, the picker merges, updates or closes it right away.
  workflow_run:
    workflows: [{_q(ci_name)}, night-shift-review]
    types: [completed]
  schedule:
    - cron: "*/20 * * * *"
  workflow_dispatch:
    inputs:
      lane:
        description: "Run only this lane (blank = every lane)"
        required: false
        default: ""

permissions:
  contents: read

jobs:
""" + "\n".join(jobs)


def review_workflow(cfg: Config, tool_repo: str = TOOL_REPO) -> str:
    queue = "\n  merge_group:" if cfg.merge_mode == "queue" else ""
    extra_with = "" if cfg.reuse_on_update else "\n      reuse_verdict: false"
    security_secret = ""
    if cfg.security_enabled:
        extra_with += "\n      security: true" + (f"\n      security_model: {cfg.security_model}" if cfg.security_model else "")
        if cfg.security_token != cfg.review_token_secret:
            security_secret = f"\n      security_claude_token: ${{{{ secrets.{cfg.security_token} }}}}"
    return f"""# Generated by `gh nightshift init`. The independent review gate for agent PRs: required check
# "review / verdict" (and "review / security" when security.enabled). Its prompt and rules
# (.night-shift/review-rules.yml) are read from the base branch, never from the PR.
name: night-shift-review

on:
  pull_request:
    types: [opened, synchronize, reopened, ready_for_review]{queue}

permissions:
  contents: read
  pull-requests: write
  issues: write
  checks: read     # reuse a passed verdict after update-branch
  actions: read

jobs:
  review:
    uses: {tool_repo}/.github/workflows/review.yml@{cfg.tool_ref}
    with:
      tool_repo: {tool_repo}
      tool_ref: {cfg.tool_ref}
      model: {cfg.review_model}{extra_with}{_runners(cfg, agent=True, github=False)}
    secrets:
      claude_token: ${{{{ secrets.{cfg.review_token_secret} }}}}{security_secret}
"""


def planner_workflow(cfg: Config, tool_repo: str = TOOL_REPO) -> str:
    crons = []
    if cfg.planner_refill_below > 0:
        crons.append(f'    - cron: "{cfg.planner_schedule}"  # refill')
    if cfg.reduce_enabled:
        crons.append(f'    - cron: "{cfg.reduce_schedule}"  # reduce')
    schedule = "\n  schedule:\n" + "\n".join(crons) if crons else ""
    # The two timers are told apart by cron string (config makes sure they differ).
    scheduled = (f"github.event.schedule == '{cfg.reduce_schedule}' && 'reduce'" if cfg.reduce_enabled else "")
    if cfg.planner_refill_below > 0:
        scheduled = (scheduled + " || " if scheduled else "") + "'refill'"
    timers = [w for w, on in (("refill", cfg.planner_refill_below > 0), ("reduce", cfg.reduce_enabled)) if on]
    token = cfg.planner_token_secret or cfg.lanes[0].token_secret
    app_with, github = _github_auth(cfg)
    options = "[prd, gap, reduce]" if cfg.reduce_enabled else "[prd, gap]"
    return f"""# Generated by `gh nightshift init`. The planner: prd and gap runs by hand, review runs when someone with
# write access comments `/night-shift plan <request>` on an issue{', ' + ' and '.join(timers) + ' on a timer' if timers else ''}.
name: night-shift-planner

on:
  workflow_dispatch:
    inputs:
      mode:
        description: "prd (from docs), gap (docs against code){' or reduce (cross-lane pass)' if cfg.reduce_enabled else ''}"
        type: choice
        options: {options}
        default: gap
      docs:
        description: "Doc paths, comma-separated (blank = planner.docs)"
        required: false
        default: ""
      lane:
        description: "Only plan for this lane (blank = all)"
        required: false
        default: ""
  issue_comment:
    types: [created]{schedule}

permissions:
  contents: read
  issues: read

jobs:
  plan:
    if: github.event_name != 'issue_comment' || startsWith(github.event.comment.body, '/night-shift plan')
    concurrency:
      group: night-shift-planner
      cancel-in-progress: false
    uses: {tool_repo}/.github/workflows/planner.yml@{cfg.tool_ref}
    with:
      mode: ${{{{ github.event_name == 'issue_comment' && 'review'
        {"|| github.event_name == 'schedule' && (" + scheduled + ") " if scheduled else ""}|| inputs.mode }}}}
      docs: ${{{{ inputs.docs || '' }}}}
      lane: ${{{{ inputs.lane || '' }}}}
      model: {cfg.planner_model}
      tool_repo: {tool_repo}
      tool_ref: {cfg.tool_ref}{app_with}{_runners(cfg, agent=True)}
    secrets:
      claude_token: ${{{{ secrets.{token} }}}}
      {github}
"""


def commands_workflow(cfg: Config, tool_repo: str = TOOL_REPO) -> str:
    app_with, github = _github_auth(cfg)
    return f"""# Generated by `gh nightshift init`. Comment commands from people with write access:
# `/night-shift take` (a person takes the ticket) and `/night-shift retry` (back in the queue, fresh attempts).
name: night-shift-commands

on:
  issue_comment:
    types: [created]

permissions:
  contents: read

jobs:
  command:
    if: >-
      github.event.comment.user.type == 'User'
      && (startsWith(github.event.comment.body, '/night-shift take')
      || startsWith(github.event.comment.body, '/night-shift retry'))
    concurrency:
      group: night-shift-command-${{{{ github.event.issue.number }}}}
      cancel-in-progress: false
    uses: {tool_repo}/.github/workflows/commands.yml@{cfg.tool_ref}
    with:
      tool_repo: {tool_repo}
      tool_ref: {cfg.tool_ref}{app_with}{_runners(cfg)}
    secrets:
      {github}
"""


def digest_workflow(cfg: Config, tool_repo: str = TOOL_REPO) -> str:
    hook = (f"\n      webhook_url: ${{{{ secrets.{cfg.digest_webhook_secret} }}}}" if cfg.digest_webhook_secret else "")
    app_with, github = _github_auth(cfg)
    w = cfg.digest_weekly_schedule
    weekly = f'\n    - cron: "{w}"  # weekly report' if w else ""
    hours = (f"\n      hours: ${{{{ github.event.schedule == '{w}' && '168' || '24' }}}}" if w else "")
    return f"""# Generated by `gh nightshift init`. The morning digest on the night-log issue, plus a roadmap refresh.
name: night-shift-digest

on:
  workflow_dispatch:
  schedule:
    - cron: "{cfg.digest_schedule}"{weekly}

permissions:
  contents: read

jobs:
  digest:
    concurrency:
      group: night-shift-digest
      cancel-in-progress: false
    uses: {tool_repo}/.github/workflows/digest.yml@{cfg.tool_ref}
    with:{hours}
      tool_repo: {tool_repo}
      tool_ref: {cfg.tool_ref}{app_with}{_runners(cfg)}
    secrets:
      {github}{hook}
"""


def template(name: str) -> str:
    return resources.files("nightshift").joinpath("templates", name).read_text(encoding="utf-8")


def ci_workflow_name(root: Path, ci_file: str) -> str:
    path = root / ".github" / "workflows" / ci_file
    if path.is_file():
        m = re.search(r"^name:\s*['\"]?([^'\"\n]+?)['\"]?\s*$", path.read_text(encoding="utf-8"), re.M)
        if m:
            return m.group(1)
    return "CI"


def config_yaml(data: dict) -> str:
    return ("# gh-nightshift config. Schema: nightshift/schema/config.schema.json in paawandesai/gh-nightshift.\n"
            "# After editing lanes, run `gh nightshift init --regenerate` to rewrite the caller workflows.\n"
            + yamlish.dumps(data) + "\n")


def files(cfg: Config, config_text: str, root: Path) -> dict[str, str]:
    """Every file init writes, by path relative to the repo root."""
    ci_name = cfg.ci_workflow_name or ci_workflow_name(root, cfg.ci_workflow)
    out = {
        ".night-shift/config.yml": config_text,
        ".github/workflows/night-shift.yml": lane_workflow(cfg, ci_name),
        ".github/workflows/night-shift-review.yml": review_workflow(cfg),
        ".github/ISSUE_TEMPLATE/night-shift-ticket.md": template("night-shift-ticket.md"),
        "docs/NIGHT_SHIFT_ISSUES.md": template("NIGHT_SHIFT_ISSUES.md"),
        "AGENT_RULES.md": template("AGENT_RULES.md"),
    }
    if cfg.planner_enabled:
        out[".github/workflows/night-shift-planner.yml"] = planner_workflow(cfg)
    out[".github/workflows/night-shift-commands.yml"] = commands_workflow(cfg)
    if cfg.digest_enabled:
        out[".github/workflows/night-shift-digest.yml"] = digest_workflow(cfg)
    if not (root / ".github/workflows" / cfg.ci_workflow).exists():
        # No CI yet: the lanes are gated on it and `test` is a required check, so write a starter one.
        out[f".github/workflows/{cfg.ci_workflow}"] = ci_template(cfg)
    return out


