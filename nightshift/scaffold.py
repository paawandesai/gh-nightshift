"""Files `gh nightshift init` writes into a project. Pure functions: config in, file text out.

The caller workflow has ONE JOB PER LANE with explicit secret names: no matrix, no `secrets[...]`
lookups, no `secrets: inherit`. A computed secret name makes GitHub send every repository secret to the
runner, so each lane job names exactly its own Claude token and its PAT. Re-run `gh nightshift init
--regenerate` after editing lanes in .night-shift/config.yml.
"""
